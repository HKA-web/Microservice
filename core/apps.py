import inspect
import logging
import os
import sys
from importlib import import_module

from django.apps import AppConfig
from django.conf import settings as djangosettings
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

logger = logging.getLogger(__name__)


class ApplicationConfig(AppConfig):
    default_auto_field = 'django.db.models.BigAutoField'
    name = 'core'
    verbose_name = _('Core')
    dependencies = []

    def ready(self):
        from django.apps import apps
        if not os.path.exists(os.path.join(apps.get_app_config('core').path, 'reloader.py')):
            with open(os.path.join(apps.get_app_config('core').path, 'reloader.py'), 'w+') as reload:
                reload.writelines('''# Do't change, this autogenerated by ERPro''')
                reload.close()
        from core.utils import search
        from library.simplehistory.models import HistoricalChanges
        for model in [model for model in self.get_models() if HistoricalChanges.__name__.lower() not in (
            base.__name__.lower() for base in model.__bases__
        ) and not any(name in model.__name__.lower() for name in ['comment'])]:
            # search.register(model)
            pass
        pass
        if not any(item in [
            'migrate',
            'makemigrations',
            'showmigrations',
            'cleanmigrations',
            'fixmigrations',
            'makemessages',
            'compilemessages',
            'makelocale',
            'compilelocale',
            'runredis',
            'dumpdata',
            'invalidate',
            'loaddata',
            'generatescretkey',
            'safesettings',
            'makelocale',
            'compilelocale',
        ] for item in sys.argv):
            import warnings
            warnings.simplefilter('ignore', category=RuntimeWarning)
            logger.debug(f'Migration not detected, {self.name}.ready will Run')
            if not hasattr(djangosettings, 'DICTIONARY'):
                setattr(djangosettings, 'DICTIONARY', {})
            if not hasattr(djangosettings, 'OPTION'):
                setattr(djangosettings, 'OPTION', {})
            try:
                from core.models import Dictionary
                for dictionary in Dictionary.objects.all():
                    data = dict(
                        name=dictionary.dictionary_name,
                        data=list(map(lambda dictionarydata: dict(
                            label=dictionarydata.label,
                            value=dictionarydata.value,
                        ), dictionary.core_dictionarydata.all())),
                    )
                    if dictionary.key not in djangosettings.DICTIONARY:
                        djangosettings.DICTIONARY.update({dictionary.key: {}})
                    if dictionary.company is not None:
                        djangosettings.DICTIONARY[dictionary.key].update({dictionary.company.pk: data})
                    else:
                        djangosettings.DICTIONARY[dictionary.key].update(data)
                from core.models import Option
                for option in Option.objects.all():
                    data = dict(
                        name=option.option_name,
                        data=option.data,
                    )
                    if option.key not in djangosettings.OPTION:
                        djangosettings.OPTION.update({option.key: {}})
                    if option.company is not None:
                        djangosettings.OPTION[option.key].update({option.company.pk: data})
                    else:
                        djangosettings.OPTION[option.key].update(data)
            except Exception as e:
                pass

            from core.fields import StatusField
            for model in [model for model in apps.get_models() if HistoricalChanges.__name__.lower() not in (
                base.__name__.lower() for base in model.__bases__
            ) and len([field for field in model._meta.get_fields() if isinstance(field, StatusField)]) > 0]:
                for field in [field for field in model._meta.get_fields() if isinstance(field, StatusField)]:
                    from core.middleware import request
                    from core.models import Dictionary, DictionaryData, Company
                    from core.utils import StringCase
                    company = Company.objects.filter(
                        pk=request().session.get('company', djangosettings.PROJECT.get('NAME'))
                        if request().session is not None
                        else djangosettings.PROJECT.get('NAME'),
                    ).first()
                    dictionary, created = Dictionary.objects.get_or_create(
                        key='%s:%s' % (model._meta.label, field.name),
                        company=company,
                        defaults=dict(
                            dictionary_name=StringCase.titlecase(field.verbose_name),
                            key='%s:%s' % (model._meta.label, field.name),
                            company=company,
                        ),
                    )
                    choices = field.prepares if len(field.prepares) else field.choices
                    choices = [dict(key=key, value=value, ) for key, value in choices]
                    if len(choices) > 0:
                        DictionaryData.objects.get_or_create(
                            value=choices[0]['key'],
                            dictionary=dictionary,
                            defaults=dict(
                                label=choices[0]['value'],
                                value=choices[0]['key'],
                                dictionary=dictionary,
                                default=True,
                            )
                        )
                    if len(field.prepares) > 0:
                        for index, prepare in enumerate([dict(key=key, value=value, ) for key, value in field.prepares]):
                            DictionaryData.objects.get_or_create(
                                value=prepare['key'],
                                dictionary=dictionary,
                                defaults=dict(
                                    label=prepare['value'],
                                    value=prepare['key'],
                                    dictionary=dictionary,
                                    default=False,
                                )
                            )
                    if not created and dictionary.dictionary_name != StringCase.titlecase(field.verbose_name):
                        dictionary.dictionary_name = StringCase.titlecase(field.verbose_name)
                        dictionary.save()
                    dictionary_data = dictionary.core_dictionarydata.all()
                    choices = [(data.value, _(data.label)) for data in dictionary_data]
                    from library.modelutils import Choices
                    choices = Choices(*choices) if len(choices) > 0 else Choices()
                    dictionary_data_defaults = dictionary_data.filter(default=True, )
                    if dictionary_data_defaults:
                        field.default = dictionary_data_defaults[0].value
                        if len(dictionary_data_defaults) > 1:
                            for dictionary_data_default in dictionary_data_defaults:
                                if dictionary_data_default.pk not in [dictionary_data_defaults[0].pk, ]:
                                    dictionary_data_default.default = False
                                    dictionary_data_default.save()
                    else:
                        if len(dictionary_data) > 0:
                            dictionary_data[0].default = True
                            dictionary_data[0].save()

                    setattr(choices, 'queryset', DictionaryData.objects.filter(dictionary__key=dictionary.key, ))

                    def company(self, company):
                        choices = [(data.value, _(data.label)) for data in (
                            getattr(self, 'queryset').filter(dictionary__company=company)
                            if isinstance(company, Company)
                            else getattr(self, 'queryset').filter(dictionary__company_id=company)
                        )]
                        return Choices(*choices) if len(choices) > 0 else Choices()

                    setattr(Choices, 'company', company)
                    setattr(field, 'choices', choices)
                    setattr(model, StringCase.pascalcase(field.name), choices)

            from core.fields import IdentifierField
            for model in [model for model in apps.get_models() if HistoricalChanges.__name__.lower() not in (
                base.__name__.lower() for base in model.__bases__
            ) and len([field for field in model._meta.get_fields() if isinstance(field, IdentifierField)]) > 0]:
                for field in [field for field in model._meta.get_fields() if isinstance(field, IdentifierField)]:
                    from core.middleware import request
                    from core.models import Company
                    from authentication.models import ContentType
                    properties = dict(
                        application=model._meta.app_label,
                        model=model._meta.model.__name__,
                    )
                    company = Company.objects.filter(
                        pk=request().session.get('company', djangosettings.PROJECT.get('NAME'))
                        if request().session is not None
                        else djangosettings.PROJECT.get('NAME'),
                    ).first()
                    content_type = ContentType.objects.get_for_model(model)
                    from core.models import Sequence
                    Sequence.objects.get_or_create(
                        company=company,
                        content_type=content_type,
                        defaults=dict(
                            company=company,
                            content_type=content_type,
                            part=field.part,
                            length=field.length,
                            prefix=field.prefix,
                            suffix=field.suffix,
                            repeater=field.repeater,
                            counter=field.counter,
                            properties=properties,
                            description=_('<p>Used for auto numbering model %(model)s on application %(application)s</p>' % properties),
                            read_only=True,
                            enable=True,
                        )
                    )

            for model in [model for model in apps.get_models() if HistoricalChanges.__name__.lower() not in (
                base.__name__.lower() for base in model.__bases__
            ) and len([field for field in model._meta.get_fields() if isinstance(field, StatusField)]) > 0]:
                for field in [field for field in model._meta.get_fields() if isinstance(field, StatusField) and field.transition]:
                    from core.middleware import request
                    from core.models import (Dictionary, DictionaryData, Company, Transition, TransitionRule, )
                    from authentication.models import ContentType
                    from core.utils import StringCase
                    company = Company.objects.filter(
                        pk=request().session.get('company', djangosettings.PROJECT.get('NAME'))
                        if request().session is not None
                        else djangosettings.PROJECT.get('NAME'),
                    ).first()
                    transition, created = Transition.objects.get_or_create(
                        pk=ContentType.objects.get_for_model(model._meta.model).pk,
                        defaults=dict(
                            transition_name=f'{model._meta.app_label}.{model._meta.model.__name__}',
                            enable=True,
                        ),
                    )
                    if created:
                        choices = field.prepares if len(field.prepares) else field.choices
                        choices = [dict(key=key, value=value, ) for key, value in choices]
                        for index, prepare in enumerate(choices):
                            if index > 0:
                                TransitionRule.objects.get_or_create(
                                    transition=transition,
                                    company=company,
                                    field=field.attname,
                                    source=choices[index - 1]['key'],
                                    target=prepare['key'],
                                    defaults=dict(
                                        transition=transition,
                                        company=company,
                                        parent=TransitionRule.objects.filter(
                                            transition=transition,
                                            company=company,
                                            field=field.attname,
                                            target=choices[index - 1]['key'],
                                        ).first(),
                                        field=field.attname,
                                        source=choices[index - 1]['key'],
                                        target=prepare['key'],
                                        rule='''return True''',
                                        process=[],
                                    ),
                                )

            modules = []
            for app_config in apps.get_app_configs():
                try:
                    modules.append(import_module('%s.%s' % (app_config.name, 'apis.views')))
                except Exception:
                    pass
            classes = []
            for module in modules:
                for member in inspect.getmembers(module, predicate=lambda member: inspect.isclass(member)):
                    classes.append(member)
            from core.consumers.mixins import RealtimeMixin
            for classe in [classe for _, classe in classes if RealtimeMixin.__name__.lower() in (
                base.__name__.lower() for base in classe.__bases__
            )]:
                from core.routings import router
                router.register(classe)
            warnings.simplefilter('default', category=RuntimeWarning)
        try:
            import zoneinfo
            from core import reloader
            logger.debug('Reload at {:%Y-%m-%d %H:%M:%S.%f}'.format(timezone.now().astimezone(zoneinfo.ZoneInfo(djangosettings.TIME_ZONE))))
        except ModuleNotFoundError as e:
            pass
        from core import signals
        __all__ = [
            signals,
        ]