if getattr(djangosettings, 'PATCH_AUTO_FIELD', True):
    import time
    from django.db.models.fields import (
        Field,
        AutoFieldMixin,
        AutoField,
        SmallAutoField,
        BigAutoField,
    )


    def __init__(self, *args, **kwargs):
        kwargs['blank'] = True
        Field.__init__(self, *args, **kwargs)


    def cast_db_type(self, connection):
        if connection.vendor == 'postgresql':
            return 'bigint'
        else:
            return self.cast_db_type(connection)


    def db_type(self, connection):
        if connection.vendor == 'postgresql':
            return 'bigint'
        else:
            return self.db_type(connection)


    def db_type_suffix(self, connection):
        if connection.vendor == 'postgresql':
            return f'GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START {int(round(time.time() * 1000))})'
        else:
            return self.db_type(connection)


    def pre_save(self, model_instance, add):
        value = getattr(model_instance, self.attname, 0)
        if add and not value > 0:
            from django.db import router, connections
            connection = connections[router.db_for_read(model_instance._meta.model)]
            cursor = connection.cursor()
            cursor.execute('SELECT pg_get_serial_sequence(%s, %s)', (self.model._meta.db_table.replace('"', ''), self.attname,))
            sequence = cursor.fetchone()[0]
            cursor.execute('SELECT nextval(%s)', (sequence,))
            value = cursor.fetchone()[0]
            if datetime.utcfromtimestamp(value/1000).day < datetime.utcnow().day:
                cursor.execute('SELECT setval(%s, %s, TRUE)', (sequence, int(round(time.time() * 1000)),))
                value = cursor.fetchone()[0]
            setattr(model_instance._meta.model, '_sequence', value)
        return getattr(model_instance, self.attname)


    AutoFieldMixin.validators = []
    AutoField.__init__ = __init__
    AutoField.pre_save = pre_save
    AutoField.cast_db_type = cast_db_type
    AutoField.db_type = db_type
    AutoField.db_type_suffix = db_type_suffix
    SmallAutoField.__init__ = __init__
    SmallAutoField.pre_save = pre_save
    SmallAutoField.cast_db_type = cast_db_type
    SmallAutoField.db_type = db_type
    SmallAutoField.db_type_suffix = db_type_suffix
    BigAutoField.__init__ = __init__
    BigAutoField.pre_save = pre_save
    BigAutoField.cast_db_type = cast_db_type
    BigAutoField.db_type = db_type
    BigAutoField.db_type_suffix = db_type_suffix
    setattr(models, 'AutoField', BigAutoField)
    setattr(models, 'SmallAutoField', BigAutoField)
    setattr(models, 'BigAutoField', BigAutoField)
